/**
 * Returns a random song index from the 100 jukebox songs.
 */
export function getRandomSongIndex(): number {
  return Math.floor(Math.random() * JUKEBOX_SONGS.length);
}

/**
 * Returns a random song from the catalog.
 */
export function getRandomSong(): JukeboxSong {
  return JUKEBOX_SONGS[getRandomSongIndex()];
}

/**
 * Get song by index (wrapped with modulo for safety).
 */
export function getSongByIndex(index: number): JukeboxSong {
  const safeIdx = ((index % JUKEBOX_SONGS.length) + JUKEBOX_SONGS.length) % JUKEBOX_SONGS.length;
  return JUKEBOX_SONGS[safeIdx];
}
